const boot = Effect.fn("test.boot")(function* () {
  const processors = yield* SessionProcessor.Service
  const session = yield* Session.Service
  const provider = yield* Provider.Service
  return { processors, session, provider }
})

it.live("PostToolUseFailure continue:false from a failed tool ends the turn and keeps the error", () =>
  provideTmpdirServer(
    ({ dir, llm }) =>
      Effect.gen(function* () {
        const { processors, session, provider } = yield* boot()
        yield* llm.tool("lookup", { query: "weather" })
        const chat = yield* session.create({})
        const parent = yield* user(chat.id, "tool")
        const msg = yield* assistant(chat.id, parent.id, path.resolve(dir))
        const mdl = yield* provider.getModel(ref.providerID, ref.modelID)
        const handle = yield* processors.create({ assistantMessage: msg, sessionID: chat.id, model: mdl })
        const value = yield* handle.process({
          user: {
            id: parent.id,
            sessionID: chat.id,
            role: "user",
            time: parent.time,
            agent: parent.agent,
            model: { providerID: ref.providerID, modelID: ref.modelID },
          } satisfies SessionV1.User,
          sessionID: chat.id,
          model: mdl,
          agent: agent(),
          system: [],
          messages: [{ role: "user", content: "tool" }],
          tools: {
            lookup: tool({
              description: "Look up information",
              inputSchema: z.object({ query: z.string() }),
              execute: async (): Promise<{ title: string; output: string; metadata: Record<string, unknown> }> => {
                throw new HookToolStop("lookup failed\n\n[Hook stopped] STOP_REASON", "STOP_REASON", {
                  cause: new Error("lookup failed"),
                })
              },
            }),
          },
        })
        const call = (yield* MessageV2.parts(msg.id)).find((part): part is SessionV1.ToolPart => part.type === "tool")
        expect(value).toBe("stop")
        expect(call?.state.status).toBe("error")
        if (call?.state.status === "error") expect(call.state.error).toContain("lookup failed")
      }),
    { config: (url) => providerCfg(url) },
  ),
)

