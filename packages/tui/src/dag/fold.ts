/**
 * Pure folding of a compose expansion's nodes under the slot that generated them (#1158). No rendering,
 * state or SDK access lives here: the panel hands in the waves and the slots the user opened, and draws
 * the rows that come back.
 */

/** The node fields folding reads; the SDK node and the stored row both fit. */
export interface DagFoldNode {
  readonly id: string
  /** The id of the expansion slot that generated the node; absent on every other node. */
  readonly expanded_from?: string
}

/** One row to draw. */
export interface DagFoldRow<T extends DagFoldNode> {
  readonly node: T
  /** Index of the wave the node sits in; undefined for a node outside every wave. */
  readonly wave: number | undefined
  /** How many slots the node sits under: 0 for a node on its own, 1 for a child of one that is not under another. */
  readonly depth: number
  /** How many nodes name this one in `expanded_from`: above 0, the node is a slot. */
  readonly children: number
  /** A slot whose children follow it. */
  readonly unfolded: boolean
}

export interface DagFold<T extends DagFoldNode> {
  /** Every node that is on show, in the order to draw: the placed ones wave by wave, then the rest. */
  readonly rows: readonly DagFoldRow<T>[]
  /** Each node left out of `rows`, and the nearest slot above it that is on show. */
  readonly hidden: ReadonlyMap<string, string>
}

/**
 * Cut every cycle of `parent` (the index of a node's slot, or -1) at the member that comes first, so that
 * every chain ends at a node that is on its own. The server never writes a cycle, but a node whose slot is
 * itself generated by that node would otherwise belong to nothing and drop out of the display.
 */
function cutCycles(parent: number[]) {
  // 0: not seen, 1: on the walk in progress, 2: settled.
  const state = new Uint8Array(parent.length)
  for (let start = 0; start < parent.length; start++) {
    if (state[start] !== 0) continue
    const walk: number[] = []
    let node = start
    while (node !== -1 && state[node] === 0) {
      state[node] = 1
      walk.push(node)
      node = parent[node]
    }
    if (node !== -1 && state[node] === 1) {
      let first = node
      for (const member of walk.slice(walk.indexOf(node))) if (member < first) first = member
      parent[first] = -1
    }
    for (const each of walk) state[each] = 2
  }
}

/**
 * Put the nodes an expansion generated under the slot that generated them. A slot is a node that another
 * node names in `expanded_from`; the slot keeps its own place among the nodes (it is the join node, and sits
 * in the wave its dependencies give it) and its children leave theirs. A slot that is not in `unfolded` is
 * folded: its children are left out of the rows. One that is unfolded is followed by them, each with its own
 * children in turn if that one is unfolded as well (a nested slot starts folded), `depth` apart.
 *
 * `waves` and `unplaced` are `computeWaves`'s answer. The children of a slot keep the order they have there:
 * by wave, then by name. A node that names an id that is not in the lists (a stale mark, or a node a replan
 * removed) is not under anything and stays where it was; so does one that names itself, and a node in a loop
 * of marks. Without marks the rows are the nodes in the order of the waves, then `unplaced`, one each.
 */
export function dagFold<T extends DagFoldNode>(
  waves: readonly (readonly T[])[],
  unplaced: readonly T[],
  unfolded: ReadonlySet<string> = new Set(),
): DagFold<T> {
  const entries: Array<{ readonly node: T; readonly wave: number | undefined }> = [
    ...waves.flatMap((wave, index) => wave.map((node) => ({ node, wave: index as number | undefined }))),
    ...unplaced.map((node) => ({ node, wave: undefined })),
  ]
  // An id that comes twice belongs to the first: nothing here is told apart by position but this lookup.
  const position = new Map<string, number>()
  for (const [index, entry] of entries.entries()) if (!position.has(entry.node.id)) position.set(entry.node.id, index)
  const parent = entries.map(({ node }, index) => {
    const slot = node.expanded_from === undefined ? undefined : position.get(node.expanded_from)
    return slot === undefined || slot === index ? -1 : slot
  })
  cutCycles(parent)
  // In display order, because the indexes are.
  const children: number[][] = entries.map(() => [])
  for (const [index, slot] of parent.entries()) if (slot !== -1) children[slot].push(index)

  const rows: DagFoldRow<T>[] = []
  const shown = new Set<number>()
  // Depth first, the first root on top of the stack last: an explicit stack, because a chain of marks can be long.
  const pending: Array<readonly [index: number, depth: number]> = []
  for (let index = entries.length - 1; index >= 0; index--) if (parent[index] === -1) pending.push([index, 0])
  while (pending.length > 0) {
    const [index, depth] = pending.pop()!
    const { node, wave } = entries[index]
    const open = children[index].length > 0 && unfolded.has(node.id)
    shown.add(index)
    rows.push({ node, wave, depth, children: children[index].length, unfolded: open })
    if (open) for (let at = children[index].length - 1; at >= 0; at--) pending.push([children[index][at], depth + 1])
  }

  const hidden = new Map<string, string>()
  for (const [index, entry] of entries.entries()) {
    if (shown.has(index)) continue
    let slot = parent[index]
    while (slot !== -1 && !shown.has(slot)) slot = parent[slot]
    // A chain ends at a node on its own, and that one is always shown.
    if (slot !== -1) hidden.set(entry.node.id, entries[slot].node.id)
  }
  return { rows, hidden }
}
