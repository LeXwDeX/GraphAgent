function isAmbiguous(codePoint: number) {
  let low = 0
  let high = AMBIGUOUS.length - 1
  while (low <= high) {
    const middle = (low + high) >> 1
    const [start, end] = AMBIGUOUS[middle]!
    if (codePoint < start) high = middle - 1
    else if (codePoint > end) low = middle + 1
    else return true
  }
  return false
}

function baseCodePoint(segment: string) {
  for (const char of segment) {
    const codePoint = char.codePointAt(0)
    if (codePoint !== undefined && Bun.stringWidth(char) > 0) return codePoint
  }
  return undefined
}

/**
 * Display width of `text` in terminal cells.
 *
 * Ambiguous-width glyphs (`◆`, `◇`, box drawing, …) count as one cell by default and
 * as two when the user selects `ambiguous_width = 2`. Always measure layout with this
 * function instead of `.length` or `Bun.stringWidth`.
 */
export function cellWidth(text: string, ambiguousWidth: AmbiguousWidth = 1): number {
  const width = Bun.stringWidth(text)
  if (ambiguousWidth === 1) return width

  // `Bun.stringWidth` already handles ANSI sequences, grapheme clusters and wide glyphs;
  // ambiguous glyphs only need one extra cell each.
  let extra = 0
  for (const { segment } of graphemes.segment(text)) {
    if (Bun.stringWidth(segment) !== 1) continue
    const base = baseCodePoint(segment)
    if (base !== undefined && isAmbiguous(base)) extra += 1
  }
  return width + extra
}

const ELLIPSIS = "…"

/**
 * Truncate `text` to at most `maxWidth` terminal cells, appending `…` when the
 * text was cut. Uses the same width model as {@link cellWidth}.
 */
export function truncateCells(text: string, maxWidth: number, ambiguousWidth: AmbiguousWidth = 1): string {
  if (maxWidth <= 0) return ""
  if (cellWidth(text, ambiguousWidth) <= maxWidth) return text

  const ellipsisWidth = cellWidth(ELLIPSIS, ambiguousWidth)
  if (maxWidth < ellipsisWidth) return ""

  let result = ""
  let width = 0
  for (const { segment } of graphemes.segment(text)) {
    const segmentWidth = cellWidth(segment, ambiguousWidth)
    if (width + segmentWidth + ellipsisWidth > maxWidth) break
    result += segment
    width += segmentWidth
  }
  return `${result}${ELLIPSIS}`
}
